#  BPY SCRIPT GENERATOR
# ══════════════════════════════════════════════════════════════════════════════

class BpyScriptGenerator:
    """Generates an executable Blender Python script from the pipeline results."""

    @staticmethod
    def generate(
        objects: list[TrackedObject],
        trajectory: CameraTrajectory | None,
        session_id: str,
    ) -> str:
        obj_lines = []
        for obj in objects:
            x, y, z = obj.blender_xyz
            obj_lines.append(
                f"    # {obj.label} (confidence={obj.confidence:.2f})\n"
                f"    bpy.ops.mesh.primitive_uv_sphere_add(location=({x:.4f}, {y:.4f}, {z:.4f}))\n"
                f"    bpy.context.object.name = '{obj.object_id}_{obj.label}'\n"
            )

        cam_lines = []
        if trajectory and trajectory.blender_path:
            cam_lines.append("    # Camera trajectory from ER 1.5 trajectory generation\n")
            cam_lines.append("    cam = bpy.data.objects.get('Camera') or bpy.ops.object.camera_add()\n")
            for i, (cx, cy, cz) in enumerate(trajectory.blender_path):
                cam_lines.append(
                    f"    bpy.context.scene.frame_set({i})\n"
                    f"    bpy.data.objects['Camera'].location = ({cx:.4f}, {cy:.4f}, {cz:.4f})\n"
                    f"    bpy.data.objects['Camera'].keyframe_insert('location', frame={i})\n"
                )

        return f"""\
# ═══════════════════════════════════════════════════════════════════════
#  APEX ENGINE — Blender Python Script
#  Session: {session_id}
#  Generated by Engine X (Apex) — gemini-robotics-er-1.5-preview
# ═══════════════════════════════════════════════════════════════════════
import bpy

def build_scene():
    # Clear existing objects
    bpy.ops.object.select_all(action='SELECT')
    bpy.ops.object.delete()

    # ── Place detected objects ─────────────────────────────────────────
{''.join(obj_lines)}
    # ── Camera trajectory ──────────────────────────────────────────────
{''.join(cam_lines)}
    # ── Scene settings ─────────────────────────────────────────────────
    bpy.context.scene.frame_start = 0
    bpy.context.scene.frame_end = {len(trajectory.blender_path) - 1 if trajectory else 240}

if __name__ == '__main__':
    build_scene()
"""


