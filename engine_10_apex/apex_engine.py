def run_apex_demo(
    image_path: str,
    prompt: str = "A cluttered desk scene with various objects",
    objects: list[str] | None = None,
) -> ApexResult:
    """
    Quick-start function demonstrating all Engine X capabilities.

    Usage:
        from apex_engine import run_apex_demo
        result = run_apex_demo("my_scene.jpg", "A kitchen counter scene")
        print(result.bpy_script)
    """
    config = ApexConfig()
    controller = ApexController(config)

    directive = ApexDirective(
        prompt=prompt,
        reference_image=image_path,
        objects_of_interest=objects or [],
        enable_trajectory=True,
        enable_consensus=True,
        enable_code_execution=True,
        enable_causal_audit=True,
    )

    return controller.render(directive)


