#  STAGE 2 — TRAJECTORY PLANNING (ThinkingPreset.LIGHT)
# ══════════════════════════════════════════════════════════════════════════════

class TrajectoryPlanningStage:
    """
    Stage 2: Uses ER 1.5's native trajectory generation capability to produce
    camera path waypoints directly.

    The model returns an ordered sequence of [y, x] points describing the
    camera's path through the scene. These are then converted to Blender
    coordinates. Previously, Bezier handles were computed manually — now ER 1.5
    generates the intermediate waypoints natively.
    """

    def __init__(self, client: GeminiERClient, config: ApexConfig) -> None:
        self.client = client
        self.config = config

    def run(
        self,
        image: bytes | str | Path,
        prompt: str,
        objects: list[TrackedObject],
        num_waypoints: int = 15,
    ) -> CameraTrajectory:
        # Build trajectory prompt from objects
        obj_list = ", ".join(f"'{o.label}'" for o in objects[:5])
        trajectory_prompt = (
            f"Generate a smooth camera trajectory that reveals the scene.\n"
            f"Key objects to frame: {obj_list}.\n"
            f"Scene description: {prompt}\n"
            f"Place a starting point on the most prominent object, then generate "
            f"{num_waypoints} trajectory waypoints for a cinematic camera move."
        )

        response = self.client.trajectory(
            image=image,
            prompt=trajectory_prompt,
            num_waypoints=num_waypoints,
            thinking=self.config.trajectory_budget,  # ThinkingPreset.LIGHT = 512
        )

        logger.info(
            "Stage 2 · Trajectory Planning: %d waypoints (thinking_budget=%d)",
            len(response.trajectory), self.config.trajectory_budget,
        )

        # Convert waypoints to Blender coordinates
        blender_path = []
        for wp in response.trajectory:
            bx, by, bz = er15_to_blender(
                wp.y, wp.x,
                scene_width_m=self.config.scene_width_m,
                scene_height_m=self.config.scene_height_m,
            )
            blender_path.append((bx, by, bz))

        return CameraTrajectory(
            waypoints=response.trajectory,
            blender_path=blender_path,
        )


# ══════════════════════════════════════════════════════════════════════════════
#  STAGE 3 — CONSENSUS ORACLE (3-pass averaging, ThinkingPreset.NONE)
# ══════════════════════════════════════════════════════════════════════════════

class ConsensusOracleStage:
    """
    Stage 3: Verifies spatial grounding using multi-pass consensus averaging.

    Per official docs and the Gemini instruction reference, querying the same
    frame multiple times and averaging coordinates is the recommended approach
    for high-precision spatial validation.

    Each pass asks: "Are these objects spatially grounded in the render?"
    Coordinates are averaged across passes to reduce false positives in the
    correction loop.
    """

    def __init__(self, client: GeminiERClient, config: ApexConfig) -> None:
        self.client = client
        self.config = config

    def run(
        self,
        rendered_image: bytes | str | Path,
        expected_objects: list[TrackedObject],
    ) -> OracleVerdict:
        if not self.config.consensus_on_oracle:
            return self._single_pass_oracle(rendered_image, expected_objects)

        # Multi-pass consensus
        query = self._build_oracle_query(expected_objects)

        if self.config.consensus_passes > 1:
            consensus_response = self.client.consensus(
                image=rendered_image,
                prompt=query,
                passes=self.config.consensus_passes,
                mode="detect",
                thinking=self.config.oracle_budget,  # ThinkingPreset.MEDIUM = 2048
            )
        else:
            consensus_response = self.client.detect(
                image=rendered_image,
                prompt=query,
                thinking=self.config.oracle_budget,
            )

        logger.info(
            "Stage 3 · Consensus Oracle: %d passes, %d objects found (thinking_budget=%d)",
            self.config.consensus_passes, len(consensus_response.boxes),
            self.config.oracle_budget,
        )

        violations, corrected = self._compare_with_expected(
            consensus_response.boxes, expected_objects
        )
        avg_confidence = (
            sum(b.confidence for b in consensus_response.boxes) / max(len(consensus_response.boxes), 1)
        )

        return OracleVerdict(
            is_grounded=len(violations) == 0,
            violations=violations,
            corrected_objects=corrected,
            confidence=avg_confidence,
            passes=self.config.consensus_passes,
        )

    def _single_pass_oracle(
        self,
        image: bytes | str | Path,
        expected: list[TrackedObject],
    ) -> OracleVerdict:
        query = self._build_oracle_query(expected)
        r = self.client.detect(image, query, thinking=self.config.oracle_budget)
        violations, corrected = self._compare_with_expected(r.boxes, expected)
        return OracleVerdict(
            is_grounded=len(violations) == 0,
            violations=violations,
            corrected_objects=corrected,
            confidence=1.0,
            passes=1,
        )

    @staticmethod
    def _build_oracle_query(objects: list[TrackedObject]) -> str:
        obj_descriptions = []
        for o in objects:
            if o.box:
                obj_descriptions.append(
                    f"'{o.label}' expected at box_2d [{o.box.ymin:.0f}, {o.box.xmin:.0f}, "
                    f"{o.box.ymax:.0f}, {o.box.xmax:.0f}]"
                )
        obj_str = "; ".join(obj_descriptions)
        return (
            f"Verify that these objects are correctly positioned in the rendered image: {obj_str}.\n"
            "For each object, return its detected box_2d in the render. "
            "If an object is missing or misplaced, include it with a note.\n"
            "Format: [{\"box_2d\": [ymin, xmin, ymax, xmax], \"label\": \"name\"}]"
        )

    @staticmethod
    def _compare_with_expected(
        detected: list[BoundingBox2D],
        expected: list[TrackedObject],
        tolerance: float = 100.0,  # normalized 0–1000, ~10% of frame
    ) -> tuple[list[str], list[TrackedObject]]:
        violations: list[str] = []
        corrected: list[TrackedObject] = []

        for obj in expected:
            match = next((d for d in detected if d.label == obj.label), None)
            if match is None:
                violations.append(f"Object '{obj.label}' not found in render")
                continue

            if obj.box:
                cy_exp, cx_exp = obj.box.center
                cy_det, cx_det = match.center
                dist = math.sqrt((cy_exp - cy_det) ** 2 + (cx_exp - cx_det) ** 2)
                if dist > tolerance:
                    violations.append(
                        f"Object '{obj.label}' deviated {dist:.1f} units "
                        f"(tolerance {tolerance})"
                    )
                    # Build corrected object from detected position
                    corrected.append(TrackedObject(
                        object_id=obj.object_id,
                        label=obj.label,
                        point=SpatialPoint(y=cy_det, x=cx_det, label=obj.label),
                        box=match,
                        blender_xyz=er15_to_blender(cy_det, cx_det),
                        confidence=match.confidence,
                    ))

        return violations, corrected


