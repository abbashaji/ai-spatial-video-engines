#  STAGE 5 — SMALL OBJECT RESOLUTION (Code Execution Tool)
# ══════════════════════════════════════════════════════════════════════════════

class SmallObjectResolutionStage:
    """
    Stage 5: Uses ER 1.5's code_execution tool to resolve ambiguous small
    or occluded objects.

    The model writes Python code to crop/zoom the image itself before
    returning coordinates. This is especially useful for objects that are
    < 5% of the frame — small items that often produce noisy bounding boxes
    in a single-pass query.

    Per official docs: tools=[types.Tool(code_execution=types.ToolCodeExecution)]
    """

    def __init__(self, client: GeminiERClient, config: ApexConfig) -> None:
        self.client = client
        self.config = config

    def resolve(
        self,
        image: bytes | str | Path,
        small_objects: list[str],
    ) -> list[BoundingBox2D]:
        """
        Resolve positions of small/occluded objects using code execution.

        The model can crop into regions of interest and return tighter
        bounding boxes than a standard single-pass detection.
        """
        if not small_objects:
            return []

        prompt = (
            f"These objects may be small or partially occluded: {', '.join(small_objects)}.\n"
            "Use code execution to zoom into relevant image regions, then return precise "
            "bounding boxes in box_2d format: [{\"box_2d\": [ymin, xmin, ymax, xmax], "
            "\"label\": \"name\"}]. All coordinates normalized 0–1000."
        )

        response = self.client.with_code(
            image=image,
            prompt=prompt,
            thinking=ThinkingPreset.LIGHT,
        )

        logger.info(
            "Stage 5 · Small Object Resolution: resolved %d objects via code execution",
            len(response.boxes),
        )

        return response.boxes


