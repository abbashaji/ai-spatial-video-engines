#  STAGE 4 — CAUSAL CHAIN AUDIT (ThinkingPreset.DEEP)
# ══════════════════════════════════════════════════════════════════════════════

class CausalChainAuditStage:
    """
    Stage 4: Multi-hop causal reasoning over the scene.

    Uses ThinkingPreset.DEEP (4096 tokens) for complex temporal + causal
    inference. This is the stage where higher thinking budget meaningfully
    reduces hallucination — the model must trace cause→effect sequences across
    multiple objects and frames.
    """

    SCHEMA = {
        "events": [
            {
                "t": "<timestamp in seconds>",
                "cause": "<what caused this>",
                "effect": "<what happened>",
                "objects": ["<object_id>"],
            }
        ],
        "physics_consistent": True,
        "reasoning": "<brief explanation of your causal analysis>",
    }

    def __init__(self, client: GeminiERClient, config: ApexConfig) -> None:
        self.client = client
        self.config = config

    def run(
        self,
        image: bytes | str | Path,
        objects: list[TrackedObject],
        prompt: str,
    ) -> CausalChain:
        obj_map = {o.object_id: o.label for o in objects}
        query = (
            f"Scene: {prompt}\n\n"
            f"Objects: {json.dumps(obj_map)}\n\n"
            "Perform a causal chain analysis. For each cause-effect pair in this scene:\n"
            "1. What happens first?\n"
            "2. What does that cause?\n"
            "3. Are the physics consistent with the object positions?\n\n"
            f"Return ONLY JSON matching this schema:\n{json.dumps(self.SCHEMA, indent=2)}"
        )

        response = self.client.reason(
            image=image,
            prompt=query,
            thinking=self.config.causal_budget,   # ThinkingPreset.DEEP = 4096 — wired!
            schema=self.SCHEMA,
        )

        logger.info(
            "Stage 4 · Causal Chain Audit complete (thinking_budget=%d)",
            self.config.causal_budget,
        )

        data = response.structured
        events = data.get("events", []) if isinstance(data, dict) else []
        physics_ok = data.get("physics_consistent", True) if isinstance(data, dict) else True
        reasoning = data.get("reasoning", "") if isinstance(data, dict) else response.raw_text

        return CausalChain(
            events=events,
            physics_consistent=physics_ok,
            reasoning=reasoning,
        )


