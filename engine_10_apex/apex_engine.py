# ══════════════════════════════════════════════════════════════════════════════
#  STAGE 1 — SPATIAL BLUEPRINT (Pointing, ThinkingPreset.NONE)
# ══════════════════════════════════════════════════════════════════════════════

class SpatialBlueprintStage:
    """
    Stage 1: Extracts [y, x] coordinates and box_2d bounding boxes for all
    objects of interest in the reference image.

    Uses ThinkingPreset.NONE (budget=0) per official ER 1.5 documentation —
    the model is fine-tuned for fast spatial pointing and does not benefit from
    additional inference-time compute for this task.

    Uses box_2d key (not bbox) to match model fine-tuning.
    """

    SYSTEM_PROMPT = """\
You are the Gemini Robotics-ER 1.5 spatial analysis module.
Your job is to locate objects precisely in the given image.

OUTPUT FORMAT — return ONLY valid JSON, no prose:
{
  "objects": [
    {
      "label": "<object name>",
      "point": [<y>, <x>],
      "box_2d": [<ymin>, <xmin>, <ymax>, <xmax>]
    }
  ]
}

Rules:
- All coordinates are integers normalized to 0–1000
- point is [y, x] format (y = vertical axis, 0 = top)
- box_2d is [ymin, xmin, ymax, xmax]
- Include every visible instance of each requested object
- Do NOT include any prose, markdown, or explanation
"""

    def __init__(self, client: GeminiERClient, config: ApexConfig) -> None:
        self.client = client
        self.config = config

    def run(
        self,
        image: bytes | str | Path,
        objects_of_interest: list[str],
        prompt: str,
    ) -> list[TrackedObject]:
        if objects_of_interest:
            query = f"Locate these objects: {', '.join(objects_of_interest)}.\n{prompt}"
        else:
            query = f"Locate all significant objects in this scene.\n{prompt}"

        full_prompt = self.SYSTEM_PROMPT + "\nUser query: " + query

        # ThinkingPreset.NONE — official recommendation for pointing tasks
        response = self.client.detect(
            image=image,
            prompt=query,
            thinking=self.config.pointing_budget,  # wired: ThinkingPreset.NONE = 0
        )

        logger.info(
            "Stage 1 · Spatial Blueprint: found %d boxes (thinking_budget=%d)",
            len(response.boxes), self.config.pointing_budget,
        )

        # Also get point centers if boxes are missing
        if not response.boxes:
            pt_response = self.client.point(
                image=image, prompt=query, thinking=self.config.pointing_budget,
            )
            return self._points_to_objects(pt_response.points)

        return self._boxes_to_objects(response.boxes)

    def _boxes_to_objects(self, boxes: list[BoundingBox2D]) -> list[TrackedObject]:
        objects = []
        for i, box in enumerate(boxes):
            cy, cx = box.center
            bx, by, bz = er15_to_blender(
                cy, cx,
                scene_width_m=self.config.scene_width_m,
                scene_height_m=self.config.scene_height_m,
            )
            objects.append(TrackedObject(
                object_id=f"obj_{i:03d}",
                label=box.label or f"object_{i}",
                point=SpatialPoint(y=cy, x=cx, label=box.label),
                box=box,
                blender_xyz=(bx, by, bz),
                confidence=box.confidence,
            ))
        return objects

    def _points_to_objects(self, points: list[SpatialPoint]) -> list[TrackedObject]:
        objects = []
        for i, pt in enumerate(points):
            bx, by, bz = er15_to_blender(
                pt.y, pt.x,
                scene_width_m=self.config.scene_width_m,
                scene_height_m=self.config.scene_height_m,
            )
            objects.append(TrackedObject(
                object_id=f"obj_{i:03d}",
                label=pt.label or f"object_{i}",
                point=pt,
                box=None,
                blender_xyz=(bx, by, bz),
                confidence=pt.confidence,
            ))
        return objects


