#  APEX CONTROLLER
# ══════════════════════════════════════════════════════════════════════════════

class ApexController:
    """
    Engine X — Apex Engine controller.

    Orchestrates all 5 stages with the correct SDK, model string, thinking
    budgets, consensus querying, trajectory generation, and code execution.
    """

    def __init__(self, config: ApexConfig | None = None) -> None:
        self.config = config or ApexConfig()
        self._init_client()
        self._init_stages()

    def _init_client(self) -> None:
        api_key = self.config.gemini_api_key or os.environ.get("GEMINI_API_KEY", "")
        if not api_key:
            logger.warning("No Gemini API key. Set GEMINI_API_KEY env var.")

        # ── NEW SDK: genai.Client (not old genai.GenerativeModel) ─────────────
        # The client is initialized once and shared via GeminiERClient adapter.
        # ThinkingConfig is set per-call by each stage, not globally.
        self._client = GeminiERClient(
            api_key=api_key,
            model=self.config.er15_model,     # gemini-robotics-er-1.5-preview
            default_thinking=ThinkingPreset.NONE,
        )
        logger.info("ApexController initialized. Model: %s", self.config.er15_model)

    def _init_stages(self) -> None:
        self._stage1 = SpatialBlueprintStage(self._client, self.config)
        self._stage2 = TrajectoryPlanningStage(self._client, self.config)
        self._stage3 = ConsensusOracleStage(self._client, self.config)
        self._stage4 = CausalChainAuditStage(self._client, self.config)
        self._stage5 = SmallObjectResolutionStage(self._client, self.config)
        self._bpy_gen = BpyScriptGenerator()

    def render(self, directive: ApexDirective) -> ApexResult:
        """
        Full Apex pipeline. Returns an ApexResult with all stage outputs.
        """
        t0 = time.time()
        session_id = directive.session_id
        logger.info("═" * 60)
        logger.info("APEX ENGINE  |  Session: %s", session_id)
        logger.info("═" * 60)

        # ── Stage 1: Spatial Blueprint ────────────────────────────────────────
        logger.info("Stage 1 · Spatial Blueprint (thinking_budget=%d = NONE)", self.config.pointing_budget)
        objects = self._stage1.run(
            directive.reference_image,
            directive.objects_of_interest,
            directive.prompt,
        )
        logger.info("  → %d objects located", len(objects))

        # ── Stage 5 sub-run: Small object resolution if enabled ───────────────
        if directive.enable_code_execution and directive.objects_of_interest:
            # Find objects that may be small (no box or small box area)
            small = [o.label for o in objects if o.box is None or o.box.area < 10000]
            if small:
                logger.info("Stage 5 · Small Object Resolution for: %s", small)
                resolved_boxes = self._stage5.resolve(directive.reference_image, small)
                # Merge resolved boxes back into objects list
                for box in resolved_boxes:
                    matching = next((o for o in objects if o.label == box.label), None)
                    if matching:
                        matching.box = box
                        cy, cx = box.center
                        matching.blender_xyz = er15_to_blender(
                            cy, cx,
                            scene_width_m=self.config.scene_width_m,
                            scene_height_m=self.config.scene_height_m,
                        )

        # ── Stage 2: Trajectory Planning ──────────────────────────────────────
        camera_trajectory = None
        if directive.enable_trajectory and objects:
            logger.info("Stage 2 · Trajectory Planning (thinking_budget=%d = LIGHT)", self.config.trajectory_budget)
            camera_trajectory = self._stage2.run(
                directive.reference_image, directive.prompt, objects
            )
            logger.info("  → %d waypoints generated", len(camera_trajectory.waypoints))

        # ── Stage 3: Consensus Oracle ─────────────────────────────────────────
        oracle_verdict = None
        if directive.enable_consensus and objects:
            passes = self.config.consensus_passes
            logger.info(
                "Stage 3 · Consensus Oracle (%d passes, thinking_budget=%d = MEDIUM)",
                passes, self.config.oracle_budget,
            )
            oracle_verdict = self._stage3.run(directive.reference_image, objects)
            logger.info(
                "  → Grounded: %s | Violations: %d | Confidence: %.2f",
                oracle_verdict.is_grounded, len(oracle_verdict.violations),
                oracle_verdict.confidence,
            )

            # Apply corrections if needed
            if not oracle_verdict.is_grounded and oracle_verdict.corrected_objects:
                correction_map = {o.object_id: o for o in oracle_verdict.corrected_objects}
                objects = [correction_map.get(o.object_id, o) for o in objects]
                logger.info("  → Applied %d corrections", len(oracle_verdict.corrected_objects))

        # ── Stage 4: Causal Chain Audit ───────────────────────────────────────
        causal_chain = None
        if directive.enable_causal_audit and objects:
            logger.info("Stage 4 · Causal Chain Audit (thinking_budget=%d = DEEP)", self.config.causal_budget)
            causal_chain = self._stage4.run(directive.reference_image, objects, directive.prompt)
            logger.info(
                "  → %d events | Physics consistent: %s",
                len(causal_chain.events), causal_chain.physics_consistent,
            )

        # ── Generate BPY script ───────────────────────────────────────────────
        bpy_script = self._bpy_gen.generate(objects, camera_trajectory, session_id)

        elapsed = time.time() - t0
        logger.info("═" * 60)
        logger.info("APEX COMPLETE | %.2fs | Session: %s", elapsed, session_id)
        logger.info("═" * 60)

        return ApexResult(
            session_id=session_id,
            objects=objects,
            camera_trajectory=camera_trajectory,
            oracle_verdict=oracle_verdict,
            causal_chain=causal_chain,
            bpy_script=bpy_script,
            metadata={
                "model": self.config.er15_model,
                "thinking_budgets": {
                    "pointing":   self.config.pointing_budget,
                    "trajectory": self.config.trajectory_budget,
                    "oracle":     self.config.oracle_budget,
                    "causal":     self.config.causal_budget,
                },
                "consensus_passes": self.config.consensus_passes,
                "sdk": "google-genai (new SDK)",
            },
            success=True,
            elapsed_s=elapsed,
        )

    def __repr__(self) -> str:
        return (
            f"ApexController(model={self.config.er15_model!r}, "
            f"consensus_passes={self.config.consensus_passes})"
        )


